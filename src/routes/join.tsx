import { createFileRoute, Link, useNavigate } from "@tanstack/react-router";
import { useEffect, useState } from "react";
import { AlertCircle, ArrowLeftCircle, ArrowRightCircle, BadgeCheck, Camera, Copy, IdCard, Loader2, Lock, Mail, Phone, ShieldCheck, User, UserPlus, Users } from "lucide-react";
import { memberApi, memberToken } from "@/lib/member-api";
import { NEEL_LINKS } from "@/components/neel-frame";
import { memberKitAsset } from "@/lib/member-kit-assets";
import { CredentialDialog, LxField, LxInput, LxPassword, passwordStrength } from "@/components/auth/auth-ui";
import type { CredentialCard } from "@/lib/credential-card";
import type { JoinTeam } from "@/lib/join-fields";
import "@/components/auth/auth-modern.css";

type Search = { ref?: string | undefined; team?: JoinTeam | undefined; place?: string | undefined };
type Sponsor = { name: string; life_id: string; placement_life_id: string; placement_side: JoinTeam };

export const Route = createFileRoute("/join")({
  validateSearch: (s: Record<string, unknown>): Search => ({ ref: typeof s["ref"] === "string" ? s["ref"] : undefined, team: s["team"] === "L" || s["team"] === "R" ? s["team"] : undefined, place: typeof s["place"] === "string" && s["place"] ? s["place"] : undefined }),
  head: () => ({
    meta: [
      { title: "Join Life OS — Member Registration" },
      { name: "description", content: "Create your Life OS member account in a minute with your sponsor's referral code." },
      { property: "og:title", content: "Join Life OS — Member Registration" },
      { property: "og:description", content: "Create your Life OS member account in a minute with your sponsor's referral code." },
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary" },
    ],
    links: NEEL_LINKS,
  }),
  component: Join,
});

const PHONE_RE = /^01[3-9]\d{8}$/;

function Join() {
  const { ref, team: linkTeam, place } = Route.useSearch();
  // Opened from "+" on the sponsor's tree: the new member goes exactly into that empty position,
  // and the sponsor stays signed in (no session switch after registering).
  const navigate = useNavigate();
  const [root, setRoot] = useState<HTMLDivElement | null>(null);
  const [card, setCard] = useState<CredentialCard | null>(null);
  const [team, setTeam] = useState<JoinTeam | undefined>(linkTeam);
  // Without a referral link the visitor types the sponsor code; the sponsor is verified live.
  const [typed, setTyped] = useState("");
  const code = (ref ?? typed).trim();
  const [sponsor, setSponsor] = useState<Sponsor | null>(null);
  const [refErr, setRefErr] = useState("");
  const [err, setErr] = useState("");
  const [busy, setBusy] = useState(false);
  const [photo, setPhoto] = useState<string | null>(null);
  const [photoErr, setPhotoErr] = useState("");
  const [phone, setPhone] = useState("");
  const [pw, setPw] = useState("");
  const [pw2, setPw2] = useState("");
  const [copied, setCopied] = useState(false);
  // The Account ID is generated by the server and shown read-only; members cannot type their own.
  const [uname, setUname] = useState<{ username: string; username_token: string } | null>(null);
  const [unameErr, setUnameErr] = useState("");
  const [unameTry, setUnameTry] = useState(0);
  useEffect(() => {
    let active = true;
    setUnameErr("");
    memberApi<{ username: string; username_token: string }>("/username/new")
      .then(u => { if (active) setUname(u); })
      .catch(() => { if (active) setUnameErr("Unable to generate an Account ID."); });
    return () => { active = false; };
  }, [unameTry]);
  useEffect(() => { setTeam(linkTeam); }, [linkTeam, ref]);
  useEffect(() => {
    let active = true;
    setSponsor(null); setRefErr("");
    if (code.length < 3) return;
    const t = setTimeout(() => {
      memberApi<Sponsor>(`/sponsor?code=${encodeURIComponent(code)}${team ? `&team=${team}` : ""}${place ? `&place=${encodeURIComponent(place)}` : ""}`)
        .then(s => { if (active) setSponsor(s); })
        .catch(e => { if (active) setRefErr(e.message === "Failed to fetch" ? "Unable to verify the sponsor right now. Please try again." : ref ? e.message : "Sponsor/Referral ID not found."); });
    }, ref ? 0 : 400);
    return () => { active = false; clearTimeout(t); };
  }, [code, team, ref, place]);

  async function pickPhoto(file?: File) {
    setPhoto(null); setPhotoErr("");
    if (!file) return;
    if (!["image/jpeg", "image/png", "image/webp"].includes(file.type) || file.size > 2 * 1024 * 1024) { setPhotoErr("Choose a JPG, PNG or WebP photo no larger than 2 MB."); return; }
    try {
      const value = await new Promise<string>((resolve, reject) => {
        const reader = new FileReader();
        reader.onload = () => typeof reader.result === "string" ? resolve(reader.result) : reject(new Error("Invalid photo"));
        reader.onerror = () => reject(new Error("Unable to read photo"));
        reader.readAsDataURL(file);
      });
      setPhoto(value);
    } catch { setPhotoErr("Unable to read photo. Please choose it again."); }
  }
  async function submit(e: React.FormEvent<HTMLFormElement>) {
    e.preventDefault();
    const fd = new FormData(e.currentTarget);
    if (!sponsor || !team || photoErr || !uname) return;
    if (pw !== pw2) { setErr("Passwords do not match."); return; }
    setErr(""); setBusy(true);
    try {
      const name = String(fd.get("name") ?? "").trim();
      const r = await memberApi<{ token: string; life_id: string }>("/register", { body: {
        name, phone, email: fd.get("email"),
        photo_base64: photo,
        username: uname.username, username_token: uname.username_token, password: pw, confirm_password: pw2,
        referral_code: code, team, accepted_terms: fd.get("terms") ? 1 : 0, ...(place ? { place } : {}),
      } });
      if (!place) memberToken.set(r.token);
      setCard({ accountId: r.life_id, password: pw, name, phone, sponsorId: sponsor.life_id, team, joinedAt: new Date(), loginUrl: `${window.location.origin}/login` });
    } catch (x) { setErr(x instanceof Error ? (x.message === "Failed to fetch" ? "Unable to connect to the registration server. Please try again." : x.message) : "Registration failed."); }
    finally { setBusy(false); }
  }

  const strength = passwordStrength(pw);
  const phoneBad = phone.length >= 11 && !PHONE_RE.test(phone);
  const mismatch = pw2.length > 0 && pw !== pw2;
  const ready = !!sponsor && !!team && !photoErr && !!uname && !busy;

  return <div className="neel-viewport neel-login-page">
    <div className="lx" ref={setRoot}>
      <div className="lx-card lx-card--reg">
        <div className="lx-reg-top">
          <Link to="/" aria-label="Life OS home"><img className="lx-logo" src={memberKitAsset("/member-kit/neel/logo-word.png")} alt="Life OS" /></Link>
          <div><h1>Create your account</h1><p>{place ? "Add a new member to your Binary Tree." : "Join Life OS in under a minute."}</p></div>
          <span className="lx-spacer" />
          {place ? <Link to="/member/tree" className="lx-toplink">← Binary Tree</Link> : <Link to="/login" className="lx-toplink">Already a member? Login</Link>}
        </div>
        <form className="lx-body" onSubmit={submit} noValidate={false}>
          <div className="lx-grid">
            <div className="lx-section"><span>1</span>Sponsor &amp; Team</div>
            <LxField label="Sponsor / Referral ID" htmlFor="sponsor">
              {ref
                ? <LxInput id="sponsor" icon={<Users />} type="text" value={sponsor?.life_id ?? ref} readOnly />
                : <LxInput id="sponsor" icon={<Users />} type="text" value={typed} onChange={e => setTyped(e.target.value)} placeholder="Sponsor code or Account ID" required maxLength={40} autoComplete="off" />}
              {code.length >= 3 && (refErr
                ? <div className="lx-sponsor lx-sponsor--err" role="alert"><AlertCircle aria-hidden="true" />{refErr}</div>
                : sponsor
                  ? <div className="lx-sponsor" role="status"><BadgeCheck aria-hidden="true" /><span>Sponsor: <b>{sponsor.name}</b> ({sponsor.life_id})</span></div>
                  : <div className="lx-sponsor lx-sponsor--wait" role="status"><Loader2 aria-hidden="true" className="animate-spin" />Checking sponsor…</div>)}
            </LxField>
            <LxField label="Choose Team">
              <div className="lx-teams" role="radiogroup" aria-label="Choose team">
                <label className="lx-team"><input type="radio" name="team" value="L" checked={team === "L"} disabled={!!linkTeam} required onChange={() => setTeam("L")} /><span className="lx-team-ico"><ArrowLeftCircle /></span><span>Left Team<small>Left side</small></span></label>
                <label className="lx-team"><input type="radio" name="team" value="R" checked={team === "R"} disabled={!!linkTeam} required onChange={() => setTeam("R")} /><span className="lx-team-ico"><ArrowRightCircle /></span><span>Right Team<small>Right side</small></span></label>
              </div>
            </LxField>

            <div className="lx-section"><span>2</span>Personal Details</div>
            <LxField label="Full Name" htmlFor="name"><LxInput id="name" name="name" icon={<User />} type="text" required maxLength={100} autoComplete="name" placeholder="Your full name" /></LxField>
            <LxField label="Mobile Number" htmlFor="phone" hint={phoneBad ? undefined : "11 digits"}>
              <LxInput id="phone" name="phone" icon={<Phone />} type="text" inputMode="tel" required pattern="01[3-9][0-9]{8}" title="01XXXXXXXXX" autoComplete="tel" placeholder="01XXXXXXXXX" maxLength={11} value={phone} onChange={e => setPhone(e.target.value.replace(/\D/g, ""))} aria-invalid={phoneBad} />
              {phoneBad && <div className="lx-hint lx-hint--err"><AlertCircle />Enter a valid Bangladeshi mobile number.</div>}
            </LxField>
            <LxField label="Email Address" htmlFor="email"><LxInput id="email" name="email" icon={<Mail />} type="email" required maxLength={120} autoComplete="email" placeholder="you@example.com" /></LxField>
            <LxField label="Profile Photo" hint="optional">
              <div className="lx-photo">
                <span className={`lx-avatar${photo ? " lx-avatar--set" : ""}`}>{photo ? <img src={photo} alt="Selected profile photo" /> : <Camera aria-hidden="true" />}</span>
                <label className="lx-btn lx-btn--soft" htmlFor="photo"><Camera aria-hidden="true" />{photo ? "Change photo" : "Upload photo"}</label>
                <input id="photo" className="lx-file" type="file" accept="image/jpeg,image/png,image/webp" onChange={e => void pickPhoto(e.currentTarget.files?.[0])} />
              </div>
              {photoErr && <div className="lx-hint lx-hint--err" role="alert"><AlertCircle />{photoErr}</div>}
            </LxField>

            <div className="lx-section"><span>3</span>Login Details</div>
            <LxField label="Your Account ID" htmlFor="username" hint="auto generated" className="lx-span2">
              <LxInput id="username" icon={<IdCard />} type="text" value={uname?.username ?? (unameErr ? "" : "Generating…")} readOnly aria-readonly="true"
                action={uname ? <button type="button" className="lx-iconbtn" aria-label="Copy Account ID" title="Copy" onClick={() => { void navigator.clipboard?.writeText(uname.username).then(() => { setCopied(true); setTimeout(() => setCopied(false), 1500); }); }}><Copy /></button> : undefined} />
              {unameErr
                ? <div className="lx-hint lx-hint--err" role="alert"><AlertCircle />{unameErr} <button type="button" className="lx-btn lx-btn--soft" style={{ height: 28, padding: "0 10px", fontSize: 12 }} onClick={() => setUnameTry(n => n + 1)}>Retry</button></div>
                : <div className={`lx-hint${copied ? " lx-hint--ok" : ""}`}><ShieldCheck />{copied ? "Copied." : "You will log in with this Account ID."}</div>}
            </LxField>
            <LxField label="Password" htmlFor="password">
              <LxPassword id="password" name="password" icon={<Lock />} required minLength={4} maxLength={72} autoComplete="new-password" placeholder="Create a password" value={pw} onChange={e => setPw(e.target.value)} />
              <div className="lx-strength" data-level={strength} aria-hidden="true"><i /><i /><i /><i /></div>
            </LxField>
            <LxField label="Confirm Password" htmlFor="confirm">
              <LxPassword id="confirm" name="confirm" icon={<Lock />} required minLength={4} maxLength={72} autoComplete="new-password" placeholder="Type it again" value={pw2} onChange={e => setPw2(e.target.value)} aria-invalid={mismatch} />
              {pw2 && <div className={`lx-hint ${mismatch ? "lx-hint--err" : "lx-hint--ok"}`}>{mismatch ? <><AlertCircle />Passwords do not match.</> : <><BadgeCheck />Passwords match.</>}</div>}
            </LxField>

            <label className="lx-terms lx-span2"><input id="terms" name="terms" type="checkbox" required /><span>I agree with the company Terms &amp; Conditions.</span></label>
            {err && <div className="lx-alert lx-span2" role="alert"><AlertCircle />{err}</div>}
            <div className="lx-submit-row lx-span2">
              <button id="submit" type="submit" className="lx-btn lx-btn--primary" disabled={!ready}>{busy ? <><Loader2 className="animate-spin" aria-hidden="true" />Creating account…</> : <><UserPlus aria-hidden="true" />Create Account</>}</button>
            </div>
          </div>
        </form>
      </div>
      <CredentialDialog open={!!card} card={card} container={root}
        continueLabel={place ? "Back to Binary Tree" : "Go to My Dashboard"}
        onContinue={() => void navigate({ to: place ? "/member/tree" : "/member" })} />
    </div>
  </div>;
}
